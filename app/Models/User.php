<?php

namespace App\Models;

use App\Notifications\WelcomeNotification;
use Database\Factories\UserFactory;
use Filament\Models\Contracts\FilamentUser;
use Filament\Panel;
use Illuminate\Contracts\Auth\MustVerifyEmail;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Foundation\Auth\User as Authenticatable;
use Illuminate\Notifications\Notifiable;
use Illuminate\Support\Facades\Log;
use Illuminate\Support\Str;
use Laravel\Sanctum\HasApiTokens;
use Throwable;

class User extends Authenticatable implements FilamentUser, MustVerifyEmail
{
    /** @use HasFactory<UserFactory> */
    use HasApiTokens, HasFactory, Notifiable;

    public const ROLE_USER = 'user';

    public const ROLE_ADMIN = 'admin';

    /**
     * Mirrors the column defaults so freshly created models serialize them.
     *
     * @var array<string, mixed>
     */
    protected $attributes = [
        'role' => self::ROLE_USER,
        'plan' => 'free',
        'license_requires_approval' => false,
        'notify_updates' => true,
        'auth_method' => 'email',
    ];

    /**
     * `role`, `plan`, `license_requires_approval` and `email_verified_at` are fillable so the admin panel can edit them. API controllers must
     * never pass raw request input to fill()/create() for this model.
     *
     * @var list<string>
     */
    protected $fillable = [
        'name',
        'email',
        'password',
        'role',
        'plan',
        'license_requires_approval',
        'notify_updates',
        'email_verified_at',
        'auth_method',
        'github_id',
        'github_login',
        'google_id',
        'avatar_url',
    ];

    /**
     * @var list<string>
     */
    protected $hidden = [
        'password',
        'remember_token',
    ];

    /**
     * @return array<string, string>
     */
    protected static function booted(): void
    {
        // Email just became verified (link, password reset, licence code, admin activation): welcome.
        static::updated(function (User $user) {
            if ($user->wasChanged('email_verified_at') && $user->email_verified_at && ! $user->getOriginal('email_verified_at')) {
                $user->sendWelcomeSafely();
            }
        });
    }

    protected function casts(): array
    {
        return [
            'email_verified_at' => 'datetime',
            'welcomed_at' => 'datetime',
            'password' => 'hashed',
            'github_id' => 'integer',
            'license_requires_approval' => 'boolean',
            'notify_updates' => 'boolean',
        ];
    }


    public function isAdmin(): bool
    {
        return $this->role === self::ROLE_ADMIN;
    }

    /** Offline licence files (.atgl) generated by the user. */
    public function licenseFiles(): HasMany
    {
        return $this->hasMany(LicenseFile::class);
    }

    /** Label of the user's plan, e.g. "Free". */
    public function planLabel(): string
    {
        return config("atglance.plans.{$this->plan}.label", ucfirst((string) $this->plan));
    }

    /**
     * Licence files the user may hold at once (they count until they expire): the "Licence file
     * limit" of their policy (custom license, then plan default, then global default), at least 1.
     */
    public function licenseFileLimit(): int
    {
        return max(1, (int) \App\Support\LicensePolicy\PolicyResolver::for($this)['max_files']);
    }

    /** GitHub users without a public/verified email get an unreachable noreply address. */
    public function hasDeliverableEmail(): bool
    {
        return ! Str::endsWith($this->email, '@users.noreply.github.com');
    }

    /**
     * Send the verification link, but never fail the caller (signup) if mail is misconfigured.
     */
    /**
     * The one welcome email, sent when the account's email becomes verified. Never twice
     * (welcomed_at), never to GitHub no-reply addresses, and never fails the caller.
     */
    public function sendWelcomeSafely(): bool
    {
        if ($this->welcomed_at || ! $this->hasVerifiedEmail() || ! $this->hasDeliverableEmail()) {
            return false;
        }

        try {
            $this->notify(new WelcomeNotification);
        } catch (Throwable $e) {
            Log::error('Could not send welcome email', ['user' => $this->id, 'error' => $e->getMessage()]);

            return false;
        }

        $this->forceFill(['welcomed_at' => now()])->saveQuietly();

        return true;
    }

    public function sendVerificationSafely(): bool
    {
        if ($this->hasVerifiedEmail() || ! $this->hasDeliverableEmail()) {
            return false;
        }

        try {
            $this->sendEmailVerificationNotification();

            return true;
        } catch (Throwable $e) {
            Log::error('Could not send verification email', ['user' => $this->id, 'error' => $e->getMessage()]);

            return false;
        }
    }

    public function canAccessPanel(Panel $panel): bool
    {
        return $this->isAdmin();
    }
}
